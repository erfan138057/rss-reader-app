_lang = "en"

def set_lang(lang: str):
    global _lang
    if lang in STRINGS:
        _lang = lang

def t(key: str, **kwargs) -> str:
    s = STRINGS.get(_lang, STRINGS["en"]).get(key, STRINGS["en"].get(key, key))
    if kwargs:
        try:
            return s.format(**kwargs)
        except Exception:
            return s
    return s
